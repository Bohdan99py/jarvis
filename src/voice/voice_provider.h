#pragma once
// ============================================================
// voice_provider.h — What a speech engine has to be able to do
//
// Провайдер синтезирует реплику В ФАЙЛ и больше ничего не решает:
// ни когда говорить (политика), ни в каком порядке (очередь), ни
// нужно ли вообще (агрегатор). Файл — не прихоть формата, а условие
// двух вещей, которые уже работают: дискового кэша и воспроизведения,
// которое можно оборвать на полуслове.
//
// Стиль приходит в SpeechRequest намерением («предупреждение»), а не
// параметрами движка. Перевести намерение в свои ручки — работа
// провайдера: Piper крутит length_scale, ElevenLabs — stability и
// speed. Поэтому промпт модели остаётся текстом, а не пультом
// звукорежиссёра.
//
// SAPI провайдером не сделан намеренно: он говорит прямо в устройство,
// файла не отдаёт, а значит не кэшируется. Он остался последним
// запасным путём в VoiceSynthesisManager — на случай, когда не смог
// никто.
// ============================================================

#include "speech_request.h"

#include <QString>

class VoiceProvider
{
public:
    virtual ~VoiceProvider() = default;

    // Короткий идентификатор — входит в ключ кэша, поэтому смена
    // провайдера сама обесценивает чужие записи.
    virtual QString id() const = 0;

    // Готов ли работать прямо сейчас: модель на диске, ключ введён.
    virtual bool isAvailable() const = 0;

    // Какой голос будет звучать. Тоже часть ключа кэша: сменили
    // голос — старые файлы перестают находиться.
    virtual QString voiceId(const SpeechRequest& req) const = 0;

    // Синтез в WAV по пути outPath. false — не смог; вызывающий
    // переходит к следующему провайдеру.
    virtual bool synthesize(const SpeechRequest& req, const QString& outPath) = 0;

    // Человеческое имя для логов и панели здоровья.
    virtual QString displayName() const { return id(); }
};
