#pragma once
// ============================================================
// dialog_cues.h — Разбор реплик, которые не являются запросами
//
// Две ситуации, в которых сообщение человека — не новая задача, а
// продолжение уже идущего разговора:
//
//   1. Оценка неуверенного ответа («почти», «нет, мне нужна другая
//      схема») — на неё нельзя отвечать как на вопрос, её надо
//      записать в обратную связь и перезадать исходный вопрос.
//   2. Ответ на вопрос, которым Джарвис закончил свою реплику.
//
// Обе — чистые текстовые эвристики без состояния и без UI, поэтому
// живут здесь, а не в MainWindow: так их можно прогнать тестом, не
// поднимая окно.
// ============================================================

#include <QString>

namespace DialogCues
{

enum class Verdict { Correct, Almost, Wrong };

// Разбирает реплику вида «почти, но мне нужна схема p2p» в вердикт и
// объяснение. Возвращает false, если это обычное сообщение.
//
// Маркер обязан открывать реплику И быть отбит знаком препинания, если
// после него идёт больше трёх слов: иначе «нет ничего лучше рекурсии»
// прочиталось бы как оценка прошлого ответа.
bool parseVerdict(const QString& text, Verdict& verdict, QString& explanation);

// Вопрос, которым закончился ответ Джарвиса, или пустая строка.
// Смотрит только в последние строки: вопрос из середины длинного
// объяснения риторический, отвечать на него никто не собирался.
QString trailingQuestion(const QString& reply);

// true, если реплика начинается с глагола просьбы, — это новая задача,
// даже если вопрос Джарвиса остался без ответа.
//
// Вводные слова перед глаголом пропускаются: «а покажи файл» и
// «ладно, открой проект» — такие же просьбы, как «покажи файл».
// Раньше проверялась только первая позиция, и любая просьба с
// разговорной затравкой считалась ответом на вопрос Джарвиса.
bool looksLikeNewRequest(const QString& text);

// true, если реплика — встречный вопрос, а не ответ.
//
// Одного знака вопроса мало: «TDD, наверное?» — это неуверенный
// ответ, а не вопрос. Поэтому требуется ещё и вопросительное слово
// в начале: «а ты умеешь читать PDF?».
bool looksLikeCounterQuestion(const QString& text);

// true, если реплику разумно считать ответом на заданный вопрос.
// Единственная точка, через которую этот вывод делают ОБА пути —
// и панель ответа, и вопрос в хвосте реплики. Раньше проверка была
// только у второго, а панель засчитывала ответом что угодно.
bool looksLikeAnswer(const QString& text);

} // namespace DialogCues
