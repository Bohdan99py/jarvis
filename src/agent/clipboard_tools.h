#pragma once
// -------------------------------------------------------
// clipboard_tools.h — История буфера обмена как инструменты
//
// clipboard_read отдаёт то, что в буфере сейчас. Вопрос «верни то,
// что я копировал ПЕРЕД этим» без истории не имел ответа вообще —
// предыдущее содержимое буфера нигде не существовало.
//
// История локальная и живёт в памяти: наружу уходит только то, что
// модель сама попросит инструментом, и только та запись, которую
// назвали. Целиком список в системный промпт не кладётся — там
// пароли, токены и куски чужих документов.
// -------------------------------------------------------

class ToolRegistry;
class ClipboardWatcher;

namespace JarvisTools {

// clipboard_history / clipboard_restore
void registerClipboardTools(ToolRegistry& registry, ClipboardWatcher* watcher);

} // namespace JarvisTools
